import { makeModel } from "./model.mjs";
function runTests(makeModel) {
  const {fresh,apply,invariant,MAX}=makeModel(); let passed=0;
  const check=(x,m)=>{if(!x)throw Error(m);passed++;};
  let s=fresh();
  const doEv=e=>{s=apply(s,e);};
  const reject=(e,label)=>{const old=s;let caught=false;try{apply(s,e);}catch{caught=true;}check(caught,label);check(s===old,"original reference");invariant(old);};
  const dollar=1000000n;
  doEv({kind:"deposit",id:"d1",owner:"alice",amount:5000n*dollar});
  doEv({kind:"deposit",id:"d2",owner:"bob",amount:5000n*dollar});
  check(invariant(s).unminted===10000n*dollar,"unminted");
  reject({kind:"deposit",id:"d1",owner:"mallory",amount:1n},"duplicate deposit");
  reject({kind:"mint",id:"bogus"},"unknown mint");
  doEv({kind:"mint",id:"d1"});doEv({kind:"mint",id:"d2"});
  reject({kind:"mint",id:"d1"},"duplicate mint");
  doEv({kind:"export",owner:"alice",amount:100n*dollar,outpoint:"tx1:0"});
  reject({kind:"import",owner:"mallory",outpoint:"tx1:0"},"outpoint owner");
  doEv({kind:"utxo_send",owner:"alice",to:"bob",from:"tx1:0",outpoint:"tx2:0"});
  reject({kind:"import",owner:"alice",outpoint:"tx1:0"},"spent outpoint");
  reject({kind:"export",owner:"bob",amount:1n,outpoint:"tx1:0"},"reused outpoint");
  doEv({kind:"import",owner:"bob",outpoint:"tx2:0"});
  doEv({kind:"send",owner:"bob",to:"alice",amount:100n*dollar});
  doEv({kind:"reserve",owner:"alice",amount:5000n*dollar});doEv({kind:"reserve",owner:"bob",amount:5000n*dollar});
  reject({kind:"burn",id:"x0",owner:"alice",destination:"alice.near",amount:1n},"reserved funds");
  const flow={kind:"settle",id:"epoch1",flows:[{from:"bob",to:"alice",amount:1200n*dollar}],obligations:new Map([["alice",1200n*dollar],["bob",-1200n*dollar]])};
  reject({...flow,obligations:new Map([["alice",1n],["bob",-1n]])},"forged obligation");
  reject({...flow,flows:[{from:"bob",to:"alice",amount:6000n*dollar}],obligations:new Map([["alice",6000n*dollar],["bob",-6000n*dollar]])},"insufficient collateral");
  doEv(flow);
  reject(flow,"settlement replay");
  check(s.margin.get("alice")===6200n*dollar && s.margin.get("bob")===3800n*dollar,"PnL");
  doEv({kind:"release",owner:"alice",amount:6200n*dollar});doEv({kind:"release",owner:"bob",amount:3800n*dollar});
  doEv({kind:"burn",id:"x1",owner:"alice",destination:"alice.near",amount:2000n*dollar});
  check(invariant(s).pending===2000n*dollar,"pending");
  reject({kind:"burn",id:"x1",owner:"bob",destination:"mallory.near",amount:1n},"exit replay");
  reject({kind:"payout_result",id:"x1",attempt:1,success:true},"unexpected callback");
  doEv({kind:"begin_payout",id:"x1"});
  reject({kind:"begin_payout",id:"x1"},"concurrent payout");
  doEv({kind:"payout_result",id:"x1",attempt:1,success:false});
  check(invariant(s).reserve===10000n*dollar,"failed callback");
  doEv({kind:"begin_payout",id:"x1"});
  reject({kind:"payout_result",id:"x1",attempt:1,success:true},"stale callback");
  doEv({kind:"payout_result",id:"x1",attempt:2,success:true});
  reject({kind:"payout_result",id:"x1",attempt:2,success:true},"double callback");
  reject({kind:"begin_payout",id:"x1"},"paid exit");
  const end=invariant(s);
  check(end.reserve===8000n*dollar&&end.outstanding===8000n*dollar&&end.pending===0n,"final backing");
  reject({kind:"send",owner:"bob",to:"alice",amount:-1n},"negative amount");
  reject({kind:"deposit",id:"overflow",owner:"alice",amount:MAX},"counter overflow");
  check(!s.deposits.has("overflow")&&!s.exits.has("x0"),"failed events leave maps intact");
  return {passed, final:Object.fromEntries(Object.entries(end).map(([k,v])=>[k,v.toString()]))};
}
console.log(JSON.stringify(runTests(makeModel),null,2));
