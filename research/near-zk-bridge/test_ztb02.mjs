import { createHash } from "node:crypto";
import { readFileSync } from "node:fs";
import assert from "node:assert/strict";
import { codecFactory } from "./codec.mjs";
import { vaultFactory } from "./vault_mock.mjs";
function runTests(c,makeVault){
  let checks=0;const ok=(b,m)=>{if(!b)throw Error(m);checks++};
  const reject=(f,m)=>{let x=false;try{f()}catch{x=true}ok(x,m)};
  const h=n=>n.toString(16).padStart(2,"0").repeat(32);
  const policy={nearGenesis:h(1),bitcoinGenesis:h(2),activation:h(3),policy:h(4),token:"usdc.testnet",vault:"bridge.testnet",property:77n};
  policy.domain=c.domain(policy);
  const s={domain:policy.domain,program:h(5),key:h(6),previousRoot:h(7),nextRoot:h(8),parentBlock:h(9),tipBlock:h(10),nearFinalBlock:h(11),depositRoot:h(12),exitRoot:h(13),epoch:1n,firstHeight:100n,lastHeight:107n,depositCount:2n,exitCount:1n,deposited:10000000n,minted:10000000n,burned:2000000n};
  const b=c.encode(s), digest=c.hex(c.statementHash(s)), packet=c.hex(c.packet(s)), limbs=c.limbs(c.statementHash(s));
  ok(b.length===392&&c.LENGTH===392,"statement size");ok(c.hex(c.encode(c.decode(b)))===c.hex(b),"round trip");ok(packet.length===80&&packet.startsWith("544c425244473031"),"packet");
  ok(limbs.every(x=>x<(1n<<128n)),"limb range");ok(c.hex(c.statementHash({...s,burned:1n}))!==digest,"changed burn");
  reject(()=>c.decode(b.slice(0,-1)),"truncation");reject(()=>c.decode(Uint8Array.from([...b,0])),"trailing byte");
  reject(()=>c.encode({...s,epoch:0n}),"epoch");reject(()=>c.encode({...s,firstHeight:108n}),"height");
  reject(()=>c.encode({...s,minted:10000001n}),"unbacked mint");reject(()=>c.encode({...s,burned:10000001n}),"overburn");
  reject(()=>c.encode({...s,depositCount:1n<<64n}),"overflow");reject(()=>c.encode({...s,extra:1}),"extra field");
  reject(()=>c.encode({...s,program:h(15).toUpperCase()}),"uppercase");
  ok(c.domain({...policy,property:78n})!==policy.domain&&c.domain({...policy,token:"usdt.testnet"})!==policy.domain,"asset separation");
  const v=makeVault(c,policy);
  const evt=(r,requested=10000000n)=>({predecessor:policy.token,receipt:h(r),event:0n,sender:"alice.testnet",recipientScriptHash:h(42),requested});
  reject(()=>v.receive({...evt(20),predecessor:"fake.testnet"}),"spoof");
  const id=v.receive(evt(20));ok(v.state().count===0&&v.state().D===0n,"pending invisible");
  reject(()=>v.receive(evt(20)),"pending duplicate");
  reject(()=>v.finalizeDeposit({id,retained:10000000n,terminal:true}),"spoof result");
  reject(()=>v.finalizeDeposit(v.issueResolution(id,10000000n,false)),"nonterminal");
  reject(()=>v.finalizeDeposit(v.issueResolution(id,10000001n)),"overcredit");
  const d=v.finalizeDeposit(v.issueResolution(id,8000000n));ok(d.amount===8000000n&&v.state().D===8000000n,"partial refund");
  reject(()=>v.receive(evt(20)),"final duplicate");
  const id2=v.receive(evt(21,2000000n));v.finalizeDeposit(v.issueResolution(id2,2000000n));
  const id3=v.receive(evt(22,1000000n));ok(v.finalizeDeposit(v.issueResolution(id3,0n))===null,"full refund");
  ok(v.state().count===2&&v.state().D===10000000n,"exact deposits");
  const proof=v.depositProof(0);ok(c.member(proof.leaf,proof.count,proof.path,proof.root),"membership");
  ok(!c.member({...proof.leaf,amount:1n},proof.count,proof.path,proof.root),"amount substitution");
  ok(!c.member({...proof.leaf,domain:h(99)},proof.count,proof.path,proof.root),"domain substitution");
  ok(!c.member({...proof.leaf,index:1n},proof.count,proof.path,proof.root),"index substitution");
  ok(!c.member(proof.leaf,3n,proof.path,proof.root),"count substitution");
  ok(!c.member(proof.leaf,proof.count,[h(99),...proof.path.slice(1)],proof.root),"path substitution");
  reject(()=>v.registerExit({id:"x",destination:"alice.testnet",amount:2000000n}),"unverified exit");
  v.registerExit(v.issueExit("x","alice.testnet",2000000n));
  reject(()=>v.registerExit(v.issueExit("x","alice.testnet",1n)),"exit replay");
  reject(()=>v.registerExit(v.issueExit("too","alice.testnet",9000000n)),"overreserve");
  const a=v.begin("x");reject(()=>v.begin("x"),"concurrent retry");
  reject(()=>v.callback({id:"x",attempt:a.attempt,success:true}),"forged callback");
  const fail=v.simulateTransfer("x",a.attempt,false);v.callback(fail);
  ok(v.status("x")==="pending"&&v.state().holdings===10000000n,"failed transfer");
  const a2=v.begin("x");
  reject(()=>v.callback(fail),"stale callback");
  const success=v.simulateTransfer("x",a2.attempt,true);
  ok(v.status("x")==="inflight"&&v.state().holdings===8000000n&&v.state().R===0n,"ambiguous callback");
  reject(()=>v.begin("x"),"no timeout resend");reject(()=>v.simulateTransfer("x",a2.attempt,true),"double transfer");
  v.callback(success);reject(()=>v.callback(success),"callback replay");
  ok(v.state().R===2000000n&&v.state().holdings===8000000n&&v.state().reserved===0n,"terminal reconciliation");
  return {checks,vector:{domain:policy.domain,statement_hex:c.hex(b),digest,packet,limbs:limbs.map(String),deposit_root:proof.root},final:{D:String(v.state().D),R:String(v.state().R),holdings:String(v.state().holdings),reserved:String(v.state().reserved)}};
}
const result=runTests(codecFactory(b=>createHash("sha256").update(b).digest()),vaultFactory);
assert.deepEqual(result.vector,JSON.parse(readFileSync(new URL("./ztb02_vector.json",import.meta.url),"utf8")));
